🎯 Student Focus

A simple web application that helps students organise academic tasks and manage deadlines.

✨ Features

- Add tasks with categories and deadlines
- Track completed and pending tasks
- Identify upcoming and overdue tasks
- Filter and delete tasks
- Save tasks using browser local storage

🛠️ Tech Stack

HTML · CSS · JavaScript

